static int32_t KSUM1[32];
static int32_t KSUM2[16];
static int32_t KSUM3[3];
static int ksum_pret = 0;

static void preparer(void)
{
  arm_vector_sum_s8(KSUM1, 14, 32, W1, 42, 0, B1);
  arm_vector_sum_s8(KSUM2, 32, 16, W2, 128, 0, B2);
  arm_vector_sum_s8(KSUM3, 16, 3, W3, 128, 0, B3);
  ksum_pret = 1;
}

int meteo_mlp_s8_predire_q(const signed char x_q[METEO_S8_NB_IN], signed char y_q[METEO_S8_NB_OUT])
{
  int8_t a1[32], a2[16], z[3];
  if (!ksum_pret) { preparer(); }
  {
    cmsis_nn_context ctx = { KSUM1, (int32_t)sizeof(KSUM1) };
    cmsis_nn_fc_params fc = { 42, 0, -128, { -128, 127 } };
    cmsis_nn_per_channel_quant_params qp = { (int32_t *)M1, (int32_t *)S1 };
    cmsis_nn_dims d_in = { 1, 1, 1, 14 }, d_w = { 14, 1, 1, 32 };
    cmsis_nn_dims d_b = { 1, 1, 1, 32 }, d_out = { 1, 1, 1, 32 };
    if (arm_fully_connected_per_channel_s8(&ctx, &fc, &qp, &d_in, (const int8_t *)x_q, &d_w, W1,
                                           &d_b, B1, &d_out, a1) != ARM_CMSIS_NN_SUCCESS)
      return -1;
  }
  {
    cmsis_nn_context ctx = { KSUM2, (int32_t)sizeof(KSUM2) };
    cmsis_nn_fc_params fc = { 128, 0, -128, { -128, 127 } };
    cmsis_nn_per_channel_quant_params qp = { (int32_t *)M2, (int32_t *)S2 };
    cmsis_nn_dims d_in = { 1, 1, 1, 32 }, d_w = { 32, 1, 1, 16 };
    cmsis_nn_dims d_b = { 1, 1, 1, 16 }, d_out = { 1, 1, 1, 16 };
    if (arm_fully_connected_per_channel_s8(&ctx, &fc, &qp, &d_in, a1, &d_w, W2,
                                           &d_b, B2, &d_out, a2) != ARM_CMSIS_NN_SUCCESS)
      return -1;
  }
  {
    cmsis_nn_context ctx = { KSUM3, (int32_t)sizeof(KSUM3) };
    cmsis_nn_fc_params fc = { 128, 0, 0, { -128, 127 } };
    cmsis_nn_per_channel_quant_params qp = { (int32_t *)M3, (int32_t *)S3 };
    cmsis_nn_dims d_in = { 1, 1, 1, 16 }, d_w = { 16, 1, 1, 3 };
    cmsis_nn_dims d_b = { 1, 1, 1, 3 }, d_out = { 1, 1, 1, 3 };
    if (arm_fully_connected_per_channel_s8(&ctx, &fc, &qp, &d_in, a2, &d_w, W3,
                                           &d_b, B3, &d_out, z) != ARM_CMSIS_NN_SUCCESS)
      return -1;
  }
  arm_softmax_s8(z, 1, METEO_S8_NB_OUT, SM_MULT, SM_SHIFT, SM_DIFF_MIN, (int8_t *)y_q);
  int best = 0;
  for (int i = 1; i < METEO_S8_NB_OUT; i++) { if (y_q[i] > y_q[best]) { best = i; } }
  return best;
}

int meteo_mlp_s8_predire(const float x_norm[METEO_S8_NB_IN], float proba[METEO_S8_NB_OUT])
{
  signed char xq[METEO_S8_NB_IN], yq[METEO_S8_NB_OUT];
  for (int i = 0; i < METEO_S8_NB_IN; i++)        /* QUANTIZE (arrondi comme TFLite) */
  {
    long v = lroundf(x_norm[i] / Q_IN_SCALE) + Q_IN_ZP;
    xq[i] = (signed char)(v < -128 ? -128 : (v > 127 ? 127 : v));
  }
  int c = meteo_mlp_s8_predire_q(xq, yq);
  if (c < 0) { return c; }
  for (int i = 0; i < METEO_S8_NB_OUT; i++)       /* DEQUANTIZE */
  {
    proba[i] = ((int)yq[i] - Q_OUT_ZP) * Q_OUT_SCALE;
  }
  return c;
}

